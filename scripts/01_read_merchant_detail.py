def load(path: Path, n_rows: int = N_ROWS) -> pd.DataFrame:
    """读取「商家明细」sheet 的前 n_rows 行（表头在第 1 行）。"""
    return pd.read_excel(path, sheet_name=SHEET, nrows=n_rows, engine="openpyxl")


def describe_fields(df: pd.DataFrame) -> pd.DataFrame:
    """把字段名、维度归属、口径说明、类型、样例值、空值数拼成一张字段字典表。"""
    rows = []
    for i, col in enumerate(df.columns, start=1):
        dim, meaning = FIELD_MEANING.get(col, ("未知", "—"))
        s = df[col]
        sample = s.dropna()
        rows.append(
            {
                "序号": i,
                "字段名": col,
                "维度": dim,
                "口径含义": meaning,
                "类型": str(s.dtype),
                "空值数": int(s.isna().sum()),
                "唯一值数": int(s.nunique(dropna=True)),
                "样例值": sample.iloc[0] if len(sample) else None,
            }
        )
    return pd.DataFrame(rows)


